export type UiIconRole = keyof typeof uiIconRoles
/** A semantic role, or any explicit `i-*` icon id. */
export type UiIcon = UiIconRole | (string & {})

export function resolveUiIcon(name: string): string {
  return name in uiIconRoles ? uiIconRoles[name as UiIconRole] : name
}
